"""Generate a standalone C++11 OJ submission from the shared kernel sources."""

import argparse
import re
from pathlib import Path

LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s*"([^"]+)"\s*$')
PRAGMA_ONCE = re.compile(r"^\s*#\s*pragma\s+once\s*$")


def amalgamate(root: Path) -> str:
    """Inline project headers once, followed by core sources and the OJ main.

    Args:
        root: Project root containing include/hrm and src/core.

    Returns:
        Deterministic submission text with standard-library includes preserved.

    Raises:
        ValueError: A local include escapes include/hrm or forms an include cycle.
        OSError: A required source file cannot be read.
    """
    root = root.resolve()
    include_root = (root / "include" / "hrm").resolve()
    emitted: set[Path] = set()
    active: set[Path] = set()

    def expand(source: Path) -> str:
        source = source.resolve()
        if source in active:
            raise ValueError(f"Include cycle at {source.relative_to(root)}")
        if source in emitted:
            return ""
        active.add(source)
        relative = source.relative_to(root).as_posix()
        chunks = [f"// Begin {relative}\n"]
        for line in source.read_text(encoding="utf-8").splitlines(keepends=True):
            match = LOCAL_INCLUDE.fullmatch(line.rstrip("\r\n"))
            if match:
                header = (root / "include" / match.group(1)).resolve()
                if not header.is_relative_to(include_root):
                    raise ValueError(f"Unsupported local include: {match.group(1)}")
                chunks.append(expand(header))
            elif not PRAGMA_ONCE.fullmatch(line.rstrip("\r\n")):
                chunks.append(line)
        chunks.append(f"\n// End {relative}\n")
        active.remove(source)
        emitted.add(source)
        return "".join(chunks)

    sources = [root / "include/hrm/core.hpp"]
    sources.extend(sorted((root / "src/core").glob("*.cpp")))
    sources.append(root / "src/oj/main.cpp")
    return "// Generated by tools/pack-oj.py; edit the original sources instead.\n" + "".join(
        (expand(source) for source in sources)
    )


def main() -> None:
    """Write the standalone submission to the requested output path."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("build/oj/main.cpp"))
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    output = args.output.resolve()
    if any(
        (
            output.is_relative_to(root / directory)
            for directory in ("include", "src", "tools", "tests")
        )
    ):
        parser.error("Output must not overwrite source directories")
    try:
        content = amalgamate(root)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(content, encoding="utf-8")
    except (OSError, ValueError) as error:
        parser.error(str(error))
    print(f"Packed OJ submission: {output}")


if __name__ == "__main__":
    main()
